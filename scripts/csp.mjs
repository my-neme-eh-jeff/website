/**
 * Appends a Content-Security-Policy for each built page to dist/_headers. Run
 * by `pnpm run build` after `qwik build`, since it hashes the served HTML.
 *
 * A static site has no server to add a nonce, so each page allows its own
 * inline scripts by sha256 hash. One rule per page: Cloudflare ignores a
 * _headers line over 2,000 characters. 404.html is served at every unknown
 * path, which no _headers rule can single out, so its policy is a <meta> tag.
 */
import { createHash } from "node:crypto";
import {
  appendFileSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DIST = join(dirname(fileURLToPath(import.meta.url)), "..", "dist");

const HEADER = "Content-Security-Policy";

/** Data blocks. The browser never runs them, so CSP never checks them. */
const DATA = /^(application\/(ld\+)?json|qwik\/.+)$/i;

// Quote-aware, so a ">" or "src=" inside an attribute value can't end a tag
// early or pass for an external script.
const SCRIPT =
  /<script\b((?:[^>"']|"[^"]*"|'[^']*')*)>([\s\S]*?)<\/script\s*>/gi;
const attrsOf = (s) =>
  new Map(
    [
      ...s.matchAll(
        /([^\s"'>/=]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'=<>`]+)))?/g,
      ),
    ].map((a) => [a[1].toLowerCase(), a[2] ?? a[3] ?? a[4] ?? ""]),
  );

const policy = (hashes) =>
  [
    "default-src 'self'",
    // Cloudflare's analytics beacon, added at runtime.
    `script-src 'self' ${hashes.join(" ")} https://static.cloudflareinsights.com`,
    // Qwik writes style attributes, and the stylesheet is inlined.
    "style-src 'self' 'unsafe-inline'",
    // The grain texture is an SVG data: URI.
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self' https://cloudflareinsights.com",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");

function hashesOf(html) {
  const hashes = new Set();
  for (const [, raw, body] of html.matchAll(SCRIPT)) {
    const attrs = attrsOf(raw);
    // Anything else non-empty is hashed, known type or not.
    if (attrs.has("src") || DATA.test(attrs.get("type") ?? "") || body === "")
      continue;
    hashes.add(
      `'sha256-${createHash("sha256").update(body).digest("base64")}'`,
    );
  }
  return [...hashes].sort();
}

const rules = [];
for (const file of readdirSync(DIST, { recursive: true }).sort()) {
  if (!file.endsWith("index.html")) continue;
  const html = readFileSync(join(DIST, file), "utf8");
  const path = `/${file.slice(0, -"index.html".length)}`;
  rules.push(`${path}\n  ${HEADER}: ${policy(hashesOf(html))}`);
}

const notFound = join(DIST, "404.html");
const page = readFileSync(notFound, "utf8");
const head = /<head\b(?:[^>"']|"[^"]*"|'[^']*')*>/i.exec(page);
if (!head) throw new Error("csp: no <head> in dist/404.html");
if (/http-equiv=["']?content-security-policy/i.test(page)) {
  throw new Error("csp: dist/404.html already has a policy");
}
// Browsers ignore frame-ancestors in a <meta> policy; X-Frame-Options covers it.
const meta = policy(hashesOf(page))
  .split("; ")
  .filter((d) => !d.startsWith("frame-ancestors "))
  .join("; ");
const at = head.index + head[0].length;
writeFileSync(
  notFound,
  `${page.slice(0, at)}<meta http-equiv="${HEADER}" content="${meta}">${page.slice(at)}`,
);

appendFileSync(
  join(DIST, "_headers"),
  "\n# Generated by scripts/csp.mjs: each page's policy, by hash.\n" +
    rules.join("\n") +
    "\n",
);
console.log(
  `csp: ${rules.length} page policies written to dist/_headers, one to dist/404.html`,
);
